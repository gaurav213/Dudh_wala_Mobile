                                            customerId,
                                            date: rowDay,
                                          ),
                                        ),
                                child: Padding(
                                  padding: const EdgeInsets.all(14),
                                  child: Column(
                                    crossAxisAlignment:
                                        CrossAxisAlignment.start,
                                    children: [
                                      Row(
                                        children: [
                                          Expanded(
                                            child: Text(
                                              '${d['customerName'] ?? 'Customer'}',
                                              style: TextStyle(
                                                fontWeight: FontWeight.w700,
                                                fontSize: 16,
                                                color: customerNoMilk
                                                    ? AppColors.danger
                                                    : null,
                                              ),
                                            ),
                                          ),
                                          if (customerNoMilk) ...[
