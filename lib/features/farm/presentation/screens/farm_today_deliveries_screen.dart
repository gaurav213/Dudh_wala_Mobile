                                                  _cantDeliverToday(
                                                    customerId:
                                                        customerId.isEmpty
                                                            ? null
                                                            : customerId,
                                                    customerName:
                                                        '${d['customerName'] ?? 'Customer'}',
                                                  );
                                                } else {
                                                  _quickAction(id, a);
                                                }
                                              },
                                              itemBuilder: (_) => [
                                                PopupMenuItem(
                                                  value: 'cant',
                                                  child: Text(l10n.cantDeliver),
                                                ),
                                                PopupMenuItem(
                                                  value: 'fail',
                                                  child: Text(l10n.fail),
                                                ),
                                              ],
                                            ),
                                        ],
                                      ),
                                      if (customerNoMilk) ...[
                                        const SizedBox(height: 6),
                                        Text(AppLocalizations.of(context).customerDoesNotWantMilk,
                                          style: TextStyle(
                                            color: AppColors.danger,
                                            fontWeight: FontWeight.w600,
                                            fontSize: 13,
                                          ),
                                        ),
                                      ],
                                      const SizedBox(height: 4),
                                      Text(
                                        [
                                          formatLitresString(qtyDisplay),
                                          '${d['deliveryShift'] ?? ''}',
                                          if ('${d['productName'] ?? ''}'
                                              .isNotEmpty)
                                            '${d['productName']}',
