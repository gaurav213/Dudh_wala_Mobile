                                  color: AppColors.danger,
                                  fontWeight: FontWeight.w700,
                                ),
                              ),
                            ),
                          ),
                        ),
                      for (final day in () {
                        final map = <String, List<Map<String, dynamic>>>{};
                        for (final d in rows) {
                          final key = '${d['deliveryDate'] ?? _from}';
                          map.putIfAbsent(key, () => []).add(d);
                        }
                        final keys = map.keys.toList()..sort();
                        return keys.map((k) {
                          final list = map[k]!;
                          list.sort((a, b) {
                            final an = _isCustomerNoMilk(a) ? 0 : 1;
                            final bn = _isCustomerNoMilk(b) ? 0 : 1;
                            return an.compareTo(bn);
                          });
                          return MapEntry(k, list);
                        });
                      }()) ...[
                        if (!_isSingleDay)
                          Padding(
                            padding: const EdgeInsets.only(top: 8, bottom: 8),
                            child: Text(
                              formatDate(DateTime.parse(day.key)),
                              style: TextStyle(
                                fontWeight: FontWeight.w800,
                                color: Dk.of(context).ink,
                                fontSize: 15,
