/// Owns the [TextEditingController] so Cancel/Save never dispose it while the
/// dialog route is still animating out (that painted the red error screen).
class _StaffExtraDialog extends StatefulWidget {
  const _StaffExtraDialog({required this.initial});

  final String initial;

  @override
  State<_StaffExtraDialog> createState() => _StaffExtraDialogState();
}

class _StaffExtraDialogState extends State<_StaffExtraDialog> {
  late final TextEditingController _controller =
      TextEditingController(text: widget.initial);

  @override
  void dispose() {
    _controller.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return AlertDialog(
      title: Text(AppLocalizations.of(context).extraMilk),
      content: TextField(
        controller: _controller,
        keyboardType: const TextInputType.numberWithOptions(decimal: true),
        decoration: InputDecoration(
          labelText: AppLocalizations.of(context).quantityL,
          helperText: AppLocalizations.of(context).replacesStaffExtra,
        ),
        autofocus: true,
      ),
      actions: [
        TextButton(
          onPressed: () => Navigator.pop(context),
          child: Text(AppLocalizations.of(context).cancel),
        ),
        FilledButton(
          onPressed: () => Navigator.pop(context, _controller.text.trim()),
          child: Text(AppLocalizations.of(context).save),
        ),
      ],
    );
  }
}

class _RecordCashDialog extends StatefulWidget {
  const _RecordCashDialog();

  @override
  State<_RecordCashDialog> createState() => _RecordCashDialogState();
}

class _RecordCashDialogState extends State<_RecordCashDialog> {
  final _amount = TextEditingController();
  String _purpose = 'BILL_PAYMENT';

  @override
  void dispose() {
    _amount.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final l10n = AppLocalizations.of(context);
    return AlertDialog(
      title: Text(l10n.farmPaisaLiya),
      content: Column(
        mainAxisSize: MainAxisSize.min,
        children: [
          TextField(
            controller: _amount,
            keyboardType: const TextInputType.numberWithOptions(decimal: true),
            decoration: InputDecoration(labelText: l10n.amountInr),
            autofocus: true,
          ),
          const SizedBox(height: 12),
          DropdownButtonFormField<String>(
            // Uncontrolled FormField: do not setState on change (avoids the old
            // initialValue rebuild bug and the deprecated `value` parameter).
            initialValue: _purpose,
            decoration: InputDecoration(labelText: AppLocalizations.of(context).purpose),
            items: [
              DropdownMenuItem(
                value: 'BILL_PAYMENT',
                child: Text(AppLocalizations.of(context).billPayment),
              ),
              DropdownMenuItem(
                value: 'ADVANCE_PAYMENT',
                child: Text(l10n.advance),
              ),
            ],
            onChanged: (v) {
              if (v != null) _purpose = v;
            },
          ),
        ],
      ),
      actions: [
        TextButton(
          onPressed: () => Navigator.pop(context),
          child: Text(l10n.cancel),
        ),
        FilledButton(
          onPressed: () {
            final amount = _amount.text.trim();
            if (amount.isEmpty) {
              Navigator.pop(context);
              return;
            }
            Navigator.pop(context, (amount: amount, purpose: _purpose));
          },
          child: Text(l10n.submit),
        ),
      ],
    );
  }
}
