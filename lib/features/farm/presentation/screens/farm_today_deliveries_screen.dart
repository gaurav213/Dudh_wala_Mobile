                                              visualDensity:
                                                  VisualDensity.compact,
                                              backgroundColor: Colors.white,
                                            ),
                                            const SizedBox(width: 6),
                                          ] else ...[
                                            if (customerId.isEmpty ||
                                                d['customerUserId'] == null ||
                                                '${d['customerUserId']}' ==
                                                    'null' ||
                                                '${d['customerUserId']}'
                                                    .isEmpty) ...[
                                              Chip(
                                                label: Text(l10n.managed),
                                                visualDensity:
                                                    VisualDensity.compact,
                                                labelStyle: const TextStyle(
                                                    fontSize: 11),
                                                backgroundColor:
                                                    Dk.of(context).foam,
                                              ),
                                              const SizedBox(width: 6),
                                            ],
                                            Chip(
                                              label: Text(statusCode,
                                                  style: const TextStyle(
                                                      fontSize: 11)),
                                              visualDensity:
                                                  VisualDensity.compact,
                                              backgroundColor:
                                                  Dk.of(context).foam,
                                            ),
                                          ],
