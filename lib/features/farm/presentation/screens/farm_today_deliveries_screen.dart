                                                      .symmetric(
                                                    horizontal: 16,
                                                    vertical: 14,
                                                  ),
                                                ),
                                                child: Text(
                                                  l10n.farmDiya,
                                                  style: const TextStyle(
                                                    fontSize: 16,
                                                    fontWeight: FontWeight.w800,
                                                  ),
                                                ),
                                              ),
                                            if (statusCode == 'DELIVERED' &&
                                                customerId.isNotEmpty)
                                              OutlinedButton(
                                                onPressed: _busy
                                                    ? null
                                                    : () => _recordPaisa(
                                                        customerId),
                                                style: OutlinedButton.styleFrom(
                                                  visualDensity:
                                                      VisualDensity.compact,
                                                  minimumSize:
                                                      const Size(56, 48),
                                                  tapTargetSize:
                                                      MaterialTapTargetSize
                                                          .shrinkWrap,
                                                ),
                                                child: Text(l10n.farmPaisaLiya),
                                              ),
                                          ],
                                        ),
                                      ],
                                    ],
                                  ),
                                ),
                              ),
                            ),
                          );
                        }),
                      ],
                    ],
                  ],
                );
              },
              loading: () => const Center(child: CircularProgressIndicator()),
              error: (e, _) => DkEmpty(
                message: '${AppLocalizations.of(context).couldNotLoad}.\n$e',
                actionLabel: 'Retry',
                onAction: () =>
                    ref.invalidate(farmTodayDeliveriesProvider(_range)),
              ),
            ),
          ),
        ),
      ],
    );
  }
